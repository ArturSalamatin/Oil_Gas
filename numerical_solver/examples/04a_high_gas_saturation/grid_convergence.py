"""Сходимость примера 04a по сетке.

ЗАЧЕМ. Замкнутое решение (GOR = Rs0) даёт дебит q_o = 4.9137e-03 м³ст/с,
расчёт при N = 50 — 4.9978e-03, расхождение 1.68 %. Это заметно больше, чем
0.45 % у примера 04, и само по себе ничего не доказывает: расхождение может
быть как ошибкой аппроксимации (тогда оно убывает с измельчением сетки), так
и систематическим смещением — ошибкой в выводе замыкания или в схеме (тогда
осталось бы при любом N).

РЕЗУЛЬТАТ. Ошибка убывает при измельчении, целевая насыщенность держится:

    N      Sg(r_w)    q_o, м³ст/с    отн. ошибка   отношение
    25     0.6991     5.082609e-03      3.3239 %
    50     0.7000     4.997788e-03      1.6832 %      1.97
    80     0.7000     4.965066e-03      1.0352 %      1.63
   120     0.7000     4.948012e-03      0.6941 %      1.49

    аналитика q_o = 4.913667e-03 м³ст/с (от сетки не зависит)

Sg стабильна с четвёртого знака начиная с N = 50 — целевое значение 0.70
достигается независимо от сетки, что и требовалось от обратного расчёта
k_rg^max: параметр выведен из замыкания, а не подогнан под дискретизацию.

Дебит сходится. Отношение ошибок 1.97 при удвоении 25 -> 50 отвечает
первому порядку схемы против потока; дальше сетка сгущается не вдвое
(50 -> 80 -> 120, отношения шагов 1.6 и 1.5), и отношения ошибок 1.63 и
1.49 совпадают с ними — то есть порядок держится единичным на всём ряду,
систематического смещения нет.

ГДЕ СОСРЕДОТОЧЕНА ОШИБКА. На фронте разгазирования p = pb. Там Sg имеет
корневую особенность Sg ~ sqrt(pb - p) (следствие n_g = 2), то есть
вертикальную касательную, а схема против потока размазывает её на 1-2
ячейки. Это же объясняет, почему ячеек с p < pb получается 22, а с Sg > 0 —
24, и почему невязка замыкания у 04a худшая в наборе (1.4e-2 против 3e-11
у табличной ОФП примера 04).

ИСТОРИЧЕСКАЯ ЗАМЕТКА (BUG-003). Сетки N >= 80 раньше не считались вовсе:
лимит дробления шага был жёстко зашит равным 5 (2^5 = 32 подшага). При
Sg ~ 0.7 обе фазы малоподвижны одновременно (kro = 0.30, krg = 6.9e-4),
якобиан плохо обусловлен по обеим переменным, и Newton требует 512
подшагов, то есть max_retries = 9. Лимит вынесен в numerics.max_retries
со значением по умолчанию 9, поэтому вся таблица считается штатными
средствами, без правки приватных полей решателя. Уменьшение dt_integration
здесь не помогает: A-retry уже дробит шаг внутри.

Запуск:
    cd numerical_solver
    .venv\\Scripts\\python examples\\04a_high_gas_saturation\\grid_convergence.py

Пять минут: четыре прогона, из них два по ~60 с.
"""

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parents[1]))   # numerical_solver/
sys.path.insert(0, str(HERE.parents[0]))   # examples/
sys.path.insert(0, str(HERE))

from example_runner import _PROTO_ROOT  # noqa: E402,F401  (подключает прототип)

from closed_form import solve_closed  # noqa: E402
from convergence import run_series  # noqa: E402
from gpn_multiphase_solver.factory import _create_relperm  # noqa: E402
from gpn_multiphase_solver.io.config import load_config  # noqa: E402

# Сетки для проверки. Все считаются на штатном numerics.max_retries = 9;
# до исправления BUG-003 лимит был 5, и N >= 80 падали с RuntimeError.
GRIDS = (25, 50, 80, 120)


def _apply(config, N):
    """Выставить сетку в копии конфига (хук run_series)."""
    config.grid.N = N


def _measure(sim, history, config):
    """Метрики прогона: Sg на забое, дебит и ошибка против замыкания.

    Дебит расчёта берётся как |G_o| на забое: поток положителен ОТ скважины
    (конвенция знаков проекта), поэтому дебит добычи — модуль потока.
    """
    grid = sim._grid
    cl = solve_closed(config, sim._energy._pvt, _create_relperm(config),
                      grid.r_centers)
    q_num = abs(history.hydro_results[-1].G_o[0])
    return {
        "Sg_well": float(history.states[-1].Sg[0]),
        "q_num": float(q_num),
        "q_ana": float(cl["q_o"]),
        # Нормировка на РАСЧЁТ, а не на аналитику — как в closed_form.
        # report_closed (строка 285). Разные знаменатели дали бы 1.683 % и
        # 1.712 % для одного и того же прогона, и README примера расходился
        # бы с тем, что печатает сам пример.
        "error": abs(q_num - cl["q_o"]) / q_num,
    }


def main():
    """Таблица: N, Sg(r_w), q_o, относительная ошибка, отношение ошибок."""
    config = load_config(HERE / "config.json")

    print("== Сходимость примера 04a по сетке ==")
    print(f"штатный numerics.max_retries = {config.numerics.max_retries} "
          f"(до BUG-003 было 5, и N >= 80 не считались)")
    print()

    rows = run_series(config, GRIDS, _apply, _measure)

    print("   N      Sg(r_w)    q_o, м³ст/с    отн. ошибка   отношение")
    prev_err = None
    for row in rows:
        ratio = "" if prev_err is None else f"{prev_err / row['error']:.2f}"
        print(f" {row['value']:4d}     {row['Sg_well']:.4f}     "
              f"{row['q_num']:.6e}     {row['error'] * 100:7.4f} %"
              f"      {ratio:>5}")
        prev_err = row["error"]

    print()
    print(f"аналитика q_o = {rows[0]['q_ana']:.6e} м³ст/с (от сетки не зависит)")
    print()

    # Целевая насыщенность — главный критерий: обратный расчёт k_rg^max
    # обязан давать 0.70 независимо от дискретизации, иначе параметр
    # подогнан под конкретную сетку, а не выведен из замыкания.
    Sg = np.array([r["Sg_well"] for r in rows])
    print(f"Sg(r_w): {Sg.min():.4f} … {Sg.max():.4f} — разброс "
          f"{(Sg.max() - Sg.min()):.4f}")
    print("Целевое 0.70 достигается на всех сетках: параметр k_rg^max выведен")
    print("из замыкания, а не подогнан под сетку.")


if __name__ == "__main__":
    main()
