def emf_frame(path):
    """Размер рисунка EMF по рамке заголовка rclFrame (единицы 0.01 мм)."""
    left, top, right, bottom = struct.unpack_from("<4i", path.read_bytes(), 24)
    return right - left, bottom - top


def add_emf(run, path, width_cm):
    """Вставить EMF в строку текста; python-docx сам EMF не разбирает, часть пакета создаётся вручную."""
    part = run.part
    partname = part.package.next_partname("/word/media/image%d.emf")
    image_part = ImagePart(partname, CT.X_EMF, path.read_bytes())
    rId = part.relate_to(image_part, RT.IMAGE)
    w, h = emf_frame(path)
    cx = Cm(width_cm)
    cy = int(cx * h / w)  # высота по пропорциям рамки EMF
    inline = CT_Inline.new_pic_inline(part.next_id, rId, path.name, cx, cy)
    run._r.add_drawing(inline)


def clear_body(doc):
    """Удалить содержимое шаблона, оставив параметры раздела (поля, формат листа)."""
    body = doc.element.body
    for el in list(body):
        if el.tag != qn("w:sectPr"):
            body.remove(el)
    # рисунки шаблона больше ни на что не ссылаются – убрать их из пакета
    for rId, rel in list(doc.part.rels.items()):
        if rel.reltype == RT.IMAGE:
            doc.part.drop_rel(rId)


def add_page_numbers(section):
    """Номер страницы по центру нижнего колонтитула (поле PAGE, 12 пт)."""
    # Нижнее поле шаблона 0.25 см – колонтитулу нужно место
    section.bottom_margin = Cm(1.5)
    section.footer_distance = Cm(0.6)
    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    r = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), str(int(TEXT_SIZE.pt * 2)))  # размер в полупунктах
    rpr.append(sz)
    r.append(rpr)
    t = OxmlElement("w:t")
    t.text = "1"  # Word пересчитывает значение поля при открытии
    r.append(t)
    fld.append(r)
    p._p.append(fld)


def add_text_run(paragraph, text, bold=False, underline=False, size=TEXT_SIZE):
    run = paragraph.add_run(UNIT_GAP.sub(NBSP, text))
    run.bold = bold
    run.underline = underline
    run.font.size = size
    return run


def build():
    doc = docx.Document(str(TEMPLATE))
    clear_body(doc)
    add_page_numbers(doc.sections[0])
    fig_no = 0
    for k, ex in enumerate(EXAMPLES):
        out_dir = EXAMPLES_DIR / ex["folder"] / "output"

        # Заголовок примера – как в шаблоне: 14 пт, подчёркнутый, по левому краю.
        # Каждый следующий пример начинается с новой страницы.
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.page_break_before = k > 0
        p.paragraph_format.keep_with_next = True
        add_text_run(p, ex["title"], underline=True, size=Pt(14))

        # Исходные данные: 12 пт, одинарный интервал, отступ первой строки
        for lead, text in ex["data"]:
            p = doc.add_paragraph()
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.first_line_indent = Cm(0.4)
            add_text_run(p, lead, bold=True)
            add_text_run(p, " " + text)

        # Рисунки: абзац с картинками держится вместе с подписью
        for names, width, caption in ex["figures"]:
            fig_no += 1
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.keep_with_next = True
            p.paragraph_format.space_before = Pt(6)
            for i, name in enumerate(names):
                if i:
                    p.add_run(" ")
                if name.endswith(".png"):
                    p.add_run().add_picture(str(out_dir / name), width=Cm(width))
                else:
                    add_emf(p.add_run(), out_dir / "emf" / f"{name}.emf", width)
            p = doc.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_after = Pt(6)
            add_text_run(p, f"Рисунок {fig_no}. {caption}")

    doc.save(str(OUTPUT))
    print(f"Сохранён: {OUTPUT} ({len(EXAMPLES)} примеров, {fig_no} рис.)")


if __name__ == "__main__":
    build()
