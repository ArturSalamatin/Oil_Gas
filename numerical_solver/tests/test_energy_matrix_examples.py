# slow (DEBT-032): 23 штатных прогона с эталоном на каждом вызове solve —
# ~280 с без 17 и 18, из них примеры 14 / 13b / 04a — 70 / 59 / 41 с, 16 — 31 с;
# 17 (останов из развитой газовой зоны, FEAT-029) — ~95 с, 18 (вход
# прототипа, VAL-005) — ~17 с. Покрытие
# не урезается: все 23 примера идут в полном прогоне (развилка предусмотрена
# планом DEBT-016, раздел «Решение о slow»).
@pytest.mark.slow
@pytest.mark.parametrize("example", ALL_EXAMPLES)
def test_matrix_matches_reference(example):
    """Коэффициенты СЛАУ совпадают с эталоном на каждом вызове solve.

    Условия: штатный конфиг примера без урезания сетки и расписания.
    Ожидание: a, b, c совпадают с эталоном при rtol=1e-12, d — с допуском
    от слагаемых ячейки (см. RTOL); границы
    a[0] и c[N-1] равны нулю точно.

    Сверка идёт НА ЛЕТУ, внутри пробы: накапливать нельзя — у 04a 1375
    вызовов при N=150, список из четырёх векторов на вызов дал бы сотни
    мегабайт.

    d сверяется в отклонениях от T_ref, которые передаёт решатель (DEBT-043).
    """
    cfg = load_config(EXAMPLES_DIR / example / "config.json")
    cfg.output.log_level = "ERROR"
    simulator, initial = SimulatorFactory.from_config(cfg)

    n_calls = [0]

    def probe(a, b, c, d, dt, T_old, T_ref, hydro_result, state_prev, bc):
        ref_a, ref_b, ref_c, ref_d, d_scale = build_reference(
            simulator._grid, simulator._pvt, cfg.rock,
            hydro_result, state_prev, dt, bc, T_ref=T_ref, with_scale=True)

        where = f"{example}: вызов {n_calls[0]}, dt={dt:g} с"
        np.testing.assert_allclose(a, ref_a, rtol=RTOL, atol=0.0,
                                   err_msg=f"{where}, поддиагональ a")
        np.testing.assert_allclose(b, ref_b, rtol=RTOL, atol=0.0,
                                   err_msg=f"{where}, главная диагональ b")
        np.testing.assert_allclose(c, ref_c, rtol=RTOL, atol=0.0,
                                   err_msg=f"{where}, наддиагональ c")
        # d_j — сумма слагаемых разного знака и у забоя меняет знак: шум
        # округления ~ eps·Σ|слагаемых|, поэтому допуск — от этой суммы
        # (_ref_d_scale). Поэлементный rtol у нуля мерил бы шум сокращения.
        d_err = np.abs(d - ref_d)
        d_lim = RTOL * (np.abs(ref_d) + d_scale)
        # Ячейку отказа ищем по маске, а не по argmax(d_err / d_lim): при
        # нулевом допуске (все слагаемые эталона в ячейке нулевые) отношение
        # даёт inf или nan (0/0), и argmax указывал на первый nan — ячейку,
        # которая не падала (BUG-023: «nan в ячейке 69» при отказе в 68).
        # ~(<=), а не >: NaN в d или d_ref обязан валить сверку, а сравнение
        # с NaN всегда ложно.
        bad = np.flatnonzero(~(d_err <= d_lim))
        assert bad.size == 0, (
            f"{where}, правая часть d: {bad.size} яч. вне допуска, первая — "
            f"{bad[0]}: |d - d_ref| = {d_err[bad[0]]:.2e} при допуске "
            f"{d_lim[bad[0]]:.2e}; d = {d[bad[0]]:.6e}, d_ref = {ref_d[bad[0]]:.6e}")

        # Границы — структура схемы, а не арифметика: строгое равенство.
        # a[0] = 0: на забое Нейман, кондуктивный поток через левую грань
        # обнулён, связи с ячейкой слева нет.
        assert a[0] == 0.0, f"{where}: a[0] обязан быть нулём (Нейман на забое)"
        # c[N-1] = 0: на контуре Дирихле, T_ext известна и ушла в d.
        assert c[-1] == 0.0, f"{where}: c[N-1] обязан быть нулём (Дирихле на контуре)"

        n_calls[0] += 1

    simulator._energy.matrix_probe = probe
    simulator.run(initial)

    assert n_calls[0] > 0, f"{example}: проба ни разу не вызвана"


