def grid(n, steps):
    """Абзац о сетке: ширины крайних ячеек логарифмической сетки и шаг по времени."""
    q = (R_EXT / R_WELL) ** (1.0 / n)  # отношение радиусов соседних граней
    first, last = R_WELL * (q - 1.0), R_EXT * (1.0 - 1.0 / q)
    return (f"Логарифмическая радиальная сетка из {n} ячеек, сгущающаяся к скважине: "
            f"ширина ячейки у скважины {first:.2g} м, у контура питания {last:.2g} м. " + steps)


