"""Решатель неизотермического притока газированной нефти к скважине: призабойная зона, модель Black Oil, уравнение энергии.

Назначение и границы модели
---------------------------
Одномерная осесимметричная задача для призабойной зоны вертикальной
скважины: фильтрация нефти с растворённым газом и свободного газа (две
фазы модели Black Oil, воды нет) совместно с переносом тепла. Гидродинамику
— давление p, газонасыщенность S_g, газосодержание R_s — решает прототип
``radial_blackoil``; пакет решает уравнение энергии (температуру T) и
управляет расчётом. Постановка и дискретные уравнения —
``doc/problem_statement.tex``; допущения и ограничения — раздел README
«Ограничения». Сведения для пользователя — README.

Устройство пакета
-----------------
- ``simulator`` — расчёт по времени: подшаги, деление шага при отказе,
  проверки состояния, запись истории;
- ``factory`` — сборка решателя по конфигурации;
- ``state``, ``bc`` — состояние, история, граничные условия, режим скважины;
- ``grid`` — логарифмическая сетка по радиусу;
- ``pvt`` — свойства флюидов (корреляции и таблицы) и ОФП;
- ``hydro`` — гидродинамика: адаптер прототипа;
- ``energy`` — уравнение энергии и баланс энергии;
- ``fluxes`` — фазовые расходы и скорости на гранях по потокам
  компонентов (выбор ячейки выше по потоку) — общий шаг для адаптера
  прототипа и для расчёта потоков по закону Дарси в тестах;
- ``mass_balance`` — баланс массы компонентов;
- ``io`` — файл конфигурации, книга Excel, запись результатов, рисунки;
- ``diagnostics`` — проверки расчёта без вывода; ``report`` — их печать и
  рисунки, конвейер ``run_case``;
- ``cli`` — команда ``gpn-solver``; ``log`` — журнал; ``units`` — единицы.

Поток данных расчёта
--------------------
Книга Excel переводится в файл конфигурации (``io.workbook_convert``);
файл конфигурации читает и проверяет ``io.config.load_config``;
``factory.SimulatorFactory.from_config`` собирает решатель и начальное
состояние; ``simulator.Simulator.run`` на каждом подшаге вызывает
гидродинамику (``hydro.prototype_adapter.PrototypeHydroAdapter``), затем
уравнение энергии (``energy.tridiag.TridiagEnergySolver``) на потоках
этого подшага и записывает ``state.SimulationHistory`` в конце каждого
интервала режима скважины; ``report.pipeline.run_case`` пишет CSV,
рисунки и печатает проверки в каталог ``output``.

Связь с прототипом
------------------
Прототип — отдельный пакет ``radial-blackoil`` в каталоге
``HydroSolverPrototype/Prototype_1.0.3``: версия 1.0.3 с изменениями
проекта (журнал — ``CHANGELOG_1.0.3.md``). Решатель требует ровно одну
его версию (``pyproject.toml``), потому что вызывает методы, которых в
исходной версии нет. Адаптер переводит состояние и режим скважины в
единицы прототипа (бар, сутки) и обратно, меняет знак потоков через
забой (у прототипа отток к скважине положителен) и отдаёт решателю
энергии потоки компонентов и фаз на всех гранях. PVT и ОФП прототип
получает тем же объектом, что видят решатель энергии и проверки:
таблицы — напрямую, корреляции — адаптером
``pvt.hydro_to_blackoil_adapter``, модель ОФП не из таблицы — таблицей
на 101 узле по газонасыщенности.

Конвенция знаков
----------------
Положительное направление — от скважины, в сторону роста r. Скорости
Дарси, объёмные и массовые расходы фаз, потоки компонентов при добыче
отрицательны. Дебит скважины в ``WellData`` — поток нефтяного компонента
через забойную грань с обратным знаком: при добыче положителен.

Связь формула → код
-------------------
Докстринги и комментарии ссылаются на уравнения постановки метками
(``eq:имя``, раздел — ``ssec:имя``), а не номерами: номера сдвигаются при
любой правке документа. В HTML-документации метка заменяется номером по
таблице ``doc/source/eq_numbers.json`` — её строит ``tools/eq_numbers.py``
из ``problem_statement.aux``. Существование меток и запрет ссылок
номерами проверяет ``tests/test_eq_references.py``.

Шаг по времени и сходимость
---------------------------
Расписание — интервалы ``time.history``; результаты записываются в конце
интервала. Внутри интервала шаг — ``time.dt_integration``, не длиннее
интервала. На подшаге сначала гидродинамика (неявная схема прототипа,
метод Ньютона), затем уравнение энергии (неявная схема,
трёхдиагональная система) на потоках этого подшага. Подшаг, на котором
метод Ньютона не сошёлся, делится пополам, не глубже
``numerics.max_retries``; дальше — отказ с сообщением. После пуска и
смены режима скважины подшаг может начинаться с
``time.dt_after_control_change`` и удваиваться. Метод Ньютона сходится
по абсолютной невязке и, если задан ``numerics.newton_cell_tol``, по
невязке каждой ячейки, отнесённой к её поровому объёму. После шага
проверяются газонасыщенность в [0, 1], давление и температура больше
нуля, газосодержание не меньше нуля, конечность значений. Схема по
времени первого порядка; погрешность по времени не контролируется —
шаг задаёт пользователь.

Тесты
-----
pytest из каталога ``numerical_solver``: быстрый уровень —
``-m "not slow"`` (несколько минут), полный — около 10 минут; метка
``slow`` — расчёты примеров по штатным конфигурациям и на сгущённых
сетках. У прототипа — свои тесты и регрессия против эталона, сверенного с
CMG IMEX (``run_tests.bat``, ``regression/`` в каталоге прототипа): тесты
пакета изменение прототипа не обнаружат. Правило докстрингов публичного
интерфейса проверяет ``tests/test_docs.py``.

Расширение
----------
- PVT-модель — наследник ``pvt.base.FullPVT`` и ветка в
  ``factory.create_pvt``;
- модель ОФП — наследник ``pvt.base.RelPermModel`` и ветка в
  ``factory.create_relperm``;
- режим скважины — наследник ``bc.WellControl``, его разбор в
  ``io.config`` и сборке расписания фабрики, поддержка в адаптере
  прототипа;
- пример — каталог в ``examples`` с файлом конфигурации (или книгой),
  таблицами CSV и README; ``main.py`` вызывает команду расчёта.

Соглашения кода
---------------
- ``numpy``, не ``math``: функции работают с массивами;
- единицы — СИ; пересчёт в единицы прототипа и книги — только на границе
  (адаптер, перевод книги);
- докстринг публичного интерфейса (``doc/source/api.rst``) — в стиле NumPy
  с русскими заголовками разделов и единицами, внутреннего кода — одна
  строка и метка уравнения;
- комментарии — физический смысл, причина решения, ожидаемый знак потока,
  выбор ячейки выше по потоку.
"""

