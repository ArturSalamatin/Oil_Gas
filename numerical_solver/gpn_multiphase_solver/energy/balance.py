"""Накопление членов баланса энергии по подшагам схемы (DEBT-013).

Баланс энергии — интегральная проверка: схема не должна терять и создавать
энергию. Компоненты (кумулятивные, от t=0 до t_n):

  ΔE(t)     — изменение запаса тепловой энергии в области
  adiab(t)  — адиабатический источник, φ·Σ_α S_α (1 + ρ_α cp_α μ_JT,α) dp/dt
  conv(t)   — работа конвективного переноса, сумма по ячейкам (обе фазы)
  jt(t)     — источник Джоуля–Томсона (обе фазы)
  deg(t)    — скрытая теплота дегазации, -L·mdot
  cond(t)   — кондуктивный поток через контур
  невязка   — ΔE - (adiab + conv + jt + deg + cond)

КОНВЕКТИВНЫЙ ЧЛЕН — СУММА ПО ЯЧЕЙКАМ, А НЕ ПОТОК ЧЕРЕЗ ГРАНИЦЫ (BUG-012).
Прежде conv(t) означал «чистую конвекцию через забой и контур» и считался
как -(flux[N] - flux[0]): внутренние грани входили в сумму дважды с
противоположными знаками и уничтожались взаимно. Это свойство
ДИВЕРГЕНТНОЙ дискретизации.

После перехода к адвективной форме (eq:energy_conv_face) такого
сворачивания нет: схема собирает вклад каждой грани с РАЗНОСТЬЮ
температур, и сумма по ячейкам к двум крайним граням не приводится.
Поэтому conv(t) суммируется по всем ячейкам — ровно те выражения, что
стоят в строках матрицы.

Физический смысл члена изменился: это уже не «энергия, вошедшая через
границы области», а работа конвективного переноса по всем ячейкам.
Интегральная проверка от этого не страдает: невязка по-прежнему
замыкается на уровне 1e-13...1e-12, потому что баланс сверяется со
схемой, а не с законом сохранения в дивергентной форме. Уравнение
энергии в адвективной форме дискретной консервативности не имеет — см.
постановку, раздел «О консервативности».

ПОЧЕМУ ЭТО ЖИВЁТ В ЯДРЕ, А НЕ В ПОСТОБРАБОТКЕ (DEBT-013). Раньше баланс
восстанавливался постфактум по записям SimulationHistory: мгновенные потоки
из hydro_results[n] умножались на шаг между записями. Это согласовано со
схемой, только пока запись = подшаг. При разреженной истории поток
последнего подшага интервала умножается на всю его длину, и невязка растёт
на три порядка (замерено, 04a: 9.98e-04 на полной истории против 2.14e-01
при записи раз в 12 подшагов). Повышение порядка квадратуры не спасает:
внутри интервала укладываются 12–288 подшагов, потоки за это время
существенно меняются, и интерполяция по двум концевым точкам этой
информации не содержит. Восстанавливать нечего — надо не терять. Поэтому
вклады считаются на КАЖДОМ подшаге и суммируются, а в историю кладутся
накопленные суммы.

ВСЕ ЧЛЕНЫ СЧИТАЮТСЯ БЕЗУСЛОВНО. Никаких ветвлений «этот член нужен только
если в конфиге λ ≠ 0 / L ≠ 0 / μ_JT ≠ 0»: член входит в формулу всегда и
обнуляется арифметикой, когда соответствующий коэффициент равен нулю.
Снимок тоже всегда содержит ПОЛНЫЙ набор ключей.

Это не стилистика, а следствие BUG-004/FEAT-016. Копия старого скрипта
у примера 03 утверждала: «кондуктивного члена нет, он и не нужен — в
конфиге λ = 0». Для 03 это верно, но проверка применяется ко всем примерам,
а у 10_deep_degassing λ ≠ 0. Девять примеров с λ = 0 маскировали пропуск
члена у десятого. Измерено после добавления члена:

    пример 10, dt   без кондукции   с кондукцией
    3600 с          4.7439e-03      4.3311e-03
     900 с          1.5098e-03      1.1095e-03
     360 с          8.5474e-04      4.5396e-04
    порядок         +0.751          +0.980

При штатном шаге выигрыш скромный (8.6 %), но `cum_cond` почти не зависит
от dt (1.286 / 1.323 / 1.323 ·10⁷ Дж) — член систематический, и при
измельчении шага он доминирует над убывающей ошибкой расщепления.

НАКОПЛЕНИЕ СЧИТАЕТСЯ ПО ПРИРАЩЕНИЯМ, а не как разность запасов от t=0
(BUG-004). Схема дискретизует Σ V (ρcp)^{n} (T^{n} - T^{n-1}): множитель
cap_j = V_j (ρcp)^{n}_j / dt стоит и в матрице, и в правой части. Разность
запасов Σ V [(ρcp)^K T^K - (ρcp)^0 T^0] отличается от неё на член
Σ_n Σ_j V T^{n-1} [(ρcp)^n - (ρcp)^{n-1}] — дрейф свойств, умноженный на
абсолютную температуру. На табличном PVT этот дрейф систематичен (B_g там
кусочно-линеен по трём узлам вместо гладкой гиперболы) и давал 20 %
невязки, не убывающей с шагом по времени.

КОЭФФИЦИЕНТЫ ПРИХОДЯТ ОТ РЕШАТЕЛЯ, а не пересчитываются здесь. Это
принципиально: пересчёт своими формулами — механизм BUG-004. Величины,
попадающие в накопитель, — те же локальные переменные, что строкой ниже
уходят в assemble_tridiag, поэтому расхождение баланса со схемой невозможно
по построению. Побочный выигрыш: (ρcp)_eff берётся на T_old, как в матрице
(cap_j), а не на новой T, как делала постобработка. При константных c_p это
эквивалентно, но если тепловые свойства станут функциями T, расхождения
не возникнет.

СЛОЙ ТЕМПЕРАТУРЫ: КОЭФФИЦИЕНТЫ — СХЕМЫ, МНОЖИТЕЛЬ — НОВЫЙ (BUG-007). Брать
у решателя правильные коэффициенты недостаточно: надо ещё умножать их на ту
же температуру, что и схема. Схема НЕЯВНАЯ — конвективные Φ⁺/Φ⁻ и
кондуктивная Q_T_ext стоят в МАТРИЦЕ, при неизвестных T^{n+1}
(\\eqref{eq:tridiag_a}, \\eqref{eq:tridiag_b}, \\eqref{eq:tridiag_c}).
В правую часть \\eqref{eq:tridiag_d} уходят только вклады с известной
T_ext (ГУ Дирихле на контуре). Поэтому оба члена считаются во второй
фазе, после решения СЛАУ.

Кондуктивный член так и был написан с самого начала, конвективный — нет:
он умножался на T^n и давал невязку ~1e-2 там, где схема замыкается с
точностью 1e-13. Измерено после правки (отн. невязка, 12 примеров):

    было   5.7e-04 ... 9.6e-03
    стало  3.4e-13 ... 7.4e-12   — уровень округлений прогонки

ОТСЮДА СЛЕДУЕТ, ЧТО НЕВЯЗКА БАЛАНСА НЕ ЕСТЬ ОШИБКА РАСЩЕПЛЕНИЯ.
Прежняя трактовка («невязка ~1e-3 — это O(dt) от расщепления гидро/тепло»)
держалась на наблюдаемом первом порядке по dt. Но порядок ~1.0 давал сам
дефект: ошибка ~Φ·dT·dt за подшаг, просуммированная по ~1/dt подшагам,
линейна по dt. После правки порядок становится ОТРИЦАТЕЛЬНЫМ (-1.1 у
примера 10, -1.6 у примера 03): невязка не убывает, а медленно растёт с
числом операций сложения — подпись округлений, а не аппроксимации.

Расщепление при этом никуда не делось и по-прежнему O(dt) — но оно влияет
на само решение T, а не на замыкание дискретного баланса. Баланс проверяет
самосогласованность уравнений схемы, и она тождественна при любом dt, если
все члены выписаны на правильных слоях.
"""

from __future__ import annotations

import numpy as np

from ..state import HydroResult, SimulationState
from ..grid.base import Grid


# Шесть накапливаемых членов. total, residual, rel_residual — производные,
# они не хранятся, а считаются из этих шести при сборке (examples/energy_balance.py).
CUMULATIVE_KEYS = ("delta_E", "cum_adiab", "cum_conv",
                   "cum_jt", "cum_deg", "cum_cond")


class EnergyBalanceAccumulator:
    """Накопление членов баланса энергии по подшагам. DEBT-013.

    Восстановить вклады по разреженной истории нельзя (см. шапку модуля),
    поэтому они считаются на каждом подшаге и суммируются.

    PVT и свойства породы накопителю НЕ нужны: все коэффициенты приходят
    от решателя уже посчитанными. Единственная его собственная зависимость —
    сетка (объёмы ячеек для суммирования по области).
    """

    def __init__(self, grid: Grid) -> None:
        self._grid = grid

        # Кумулятивные суммы (Дж), общие для всего прогона
        self.delta_E = 0.0
        self.cum_adiab = 0.0
        self.cum_conv = 0.0
        self.cum_jt = 0.0
        self.cum_deg = 0.0
        self.cum_cond = 0.0

        # Проводимость контура и T_ext текущего подшага: приходят в
        # add_substep (проводимость зависит от λ_eff, то есть от
        # насыщенности; T_ext задаётся интервалом истории и может
        # меняться), а используются в add_accumulation — там уже известна
        # новая температура.
        self._Q_T_ext = 0.0
        self._T_ext = 0.0

        # Конвективные коэффициенты подшага. Как и проводимость контура,
        # они приходят в add_substep (их считает решатель), но применяются
        # в add_accumulation: схема НЕЯВНАЯ, Φ стоят в матрице СЛАУ при
        # неизвестных T^{n+1} (tridiag.assemble_tridiag), а не в правой
        # части. Умножать их на T^n — это BUG-007: невязка 1e-2 вместо 1e-12.
        # None, а не нули: отличаем "подшага ещё не было" от "поток нулевой".
        self._Phi_plus = None
        self._Phi_minus = None
        self._dt_substep = None

    # ──────────────────────────────────────────────────────
    # Часть 1: вклады, зависящие только от коэффициентов шага
    # ──────────────────────────────────────────────────────

    def add_substep(self, hydro_result: HydroResult,
                    state_prev: SimulationState, dt: float,
                    props: dict, Phi_o: np.ndarray, Phi_g: np.ndarray,
                    Q_T_ext: float, J_jt: np.ndarray,
                    Q_ad: np.ndarray, Q_deg: np.ndarray,
                    T_ext: float) -> None:
        """Вклад источников за подшаг. Коэффициенты приходят от решателя
        уже посчитанными — пересчитывать их нельзя (BUG-004).
        """
        grid = self._grid
        V = grid.volumes

        # Проводимость контура нужна на второй фазе (add_accumulation),
        # где известна T^{n+1}. Запоминаем ту, что посчитал решатель,
        # вместе с T_ext текущего интервала.
        self._Q_T_ext = Q_T_ext
        self._T_ext = T_ext

        # ── Конвекция (обе фазы): ОТЛОЖЕНА до add_accumulation ──
        # Φ_α = ρ_α cp_α Q_α (eq. 23). Знак: Q < 0 (поток к скважине) ⇒ Φ < 0.
        # Φ приходит с ВСЕХ граней, upstream раздельно по каждой фазе —
        # иначе при противотоке фаз (Φ_o и Φ_g разных знаков на одной
        # грани) расщепление Φ⁺/Φ⁻ было бы неверным.
        #
        # Здесь только СОХРАНЯЕМ: множитель T известен лишь после решения
        # СЛАУ (BUG-007). Сам вклад считается в add_accumulation — суммой
        # по ячейкам, а не разностью крайних потоков (BUG-012).
        self._Phi_plus = np.maximum(Phi_o, 0.0) + np.maximum(Phi_g, 0.0)
        self._Phi_minus = np.minimum(Phi_o, 0.0) + np.minimum(Phi_g, 0.0)
        self._dt_substep = dt

        # ── Джоуль–Томсон (обе фазы) ──
        # J_jt[j] — вклад JT в уравнение ячейки j (tridiag.compute_jt,
        # eq:QJT_disc), в адвективной форме: вклады двух граней ячейки,
        # каждый с перепадом давления. Сумма по ячейкам к двум крайним
        # граням НЕ сворачивается (BUG-012) — но это и не требуется:
        # решатель ставит в правую часть d[j] именно J_jt[j], и мы обязаны
        # суммировать ровно то же самое. Этот инвариант не зависит от формы
        # члена и потому пережил правку BUG-012 без изменений.
        # μ_JT здесь по upstream-ячейке — так считает схема; постобработка
        # брала по ячейке грани, и при μ_JT = μ_JT(p,T) это дало бы
        # расхождение (при константах, как во всех PVT проекта, разницы нет).
        # При μ_JT = 0 (примеры 01, 07, 09) член обнуляется сам.
        self.cum_jt += np.sum(J_jt) * dt

        # ── Адиабатика (обе фазы) ──
        # Q_ad = φ Σ_α S_α (1 + ρ_α cp_α μ_JT,α) dp/dt, Вт/м³ (eq. 29).
        # Решатель ставит V[j]·Q_ad[j] в правую часть — суммируем то же.
        self.cum_adiab += np.sum(V * Q_ad) * dt

        # ── Скрытая теплота дегазации ──
        # Q_deg = -L·mdot, Вт/м³ (eq:Qdeg_disc, eq:mdot_disc).
        # Решатель ставит V[j]·Q_deg[j]
        # в правую часть. При L = 0 (примеры 01, 02, 07, 08) член нулевой.
        self.cum_deg += np.sum(V * Q_deg) * dt

        # props оставлен в сигнатуре: он нужен add_accumulation (rho_cp_eff).
        # hydro_result и state_prev тоже больше не используются — контракт
        # единый для всех реализаций EnergySolver (energy/base.py:46-50),
        # менять его ради одного члена незачем.
        del props

    # ──────────────────────────────────────────────────────
    # Часть 2: вклады, требующие T^{n+1}
    # ──────────────────────────────────────────────────────

    def add_accumulation(self, T_new: np.ndarray, T_prev: np.ndarray,
                         rho_cp_eff: np.ndarray, dt: float) -> None:
        """Накопление ΔE и кондуктивный член — требуют T^{n+1},
        поэтому вызываются ПОСЛЕ решения СЛАУ.
        """
        V = self._grid.volumes
        N = self._grid.N

        # ── Конвекция (обе фазы) ──
        # Считается ЗДЕСЬ, а не в add_substep, потому что схема неявная:
        # Φ⁺/Φ⁻ стоят в матрице СЛАУ при неизвестных T^{n+1}
        # (tridiag.assemble_tridiag), и только контурный вклад
        # -Φ⁻_N·T_ext уходит в правую часть d[N-1], потому что T_ext
        # известна заранее.
        #
        # Умножение тех же Φ на T^n давало невязку баланса ~1e-2 при
        # самосогласованности схемы 1e-13 (BUG-007). Ошибка за подшаг
        # ~Φ(T^{n+1}-T^n)Δt систематична, пока идёт охлаждение, поэтому
        # копилась, а не сокращалась.
        #
        # АДВЕКТИВНАЯ ФОРМА (BUG-012). Схема дискретизует конвекцию как
        # вклад каждой грани с РАЗНОСТЬЮ температур (eq:energy_conv_face):
        #
        #     F_j = Φ⁺_{j-1/2}·(T_j − T_{j-1}) + Φ⁻_{j+1/2}·(T_{j+1} − T_j)
        #
        # Сумма F_j по ячейкам НЕ сворачивается к разности потоков через
        # забой и контур: внутренние грани больше не уничтожаются взаимно.
        # Прежняя формула -(flux[N] - flux[0]) опиралась именно на такое
        # сворачивание и после перехода к адвективной форме неверна.
        # Поэтому суммируем по ячейкам — ровно те выражения, что стоят
        # в строках матрицы.
        #
        # Соседи: слева от ячейки 0 — она сама (разность нулевая, забойная
        # грань вклада не даёт, ГУ Неймана), справа от N-1 — T_ext (ГУ
        # Дирихле). Те же соглашения, что в assemble_tridiag.
        if self._Phi_plus is None:
            raise RuntimeError(
                "add_accumulation вызван без предшествующего add_substep: "
                "конвективные коэффициенты подшага неизвестны")

        T_left = np.concatenate(([T_new[0]], T_new[:-1]))    # [N]: T_{j-1}
        T_right = np.concatenate((T_new[1:], [self._T_ext]))  # [N]: T_{j+1}

        F = (self._Phi_plus[0:N] * (T_new - T_left)
             + self._Phi_minus[1:N + 1] * (T_right - T_new))

        # Знак: F_j стоит в ЛЕВОЙ части уравнения (eq:energy_disc_full)
        # рядом с накоплением, поэтому вклад конвекции в энергию области
        # равен -ΣF_j. При штатном притоке (Φ < 0, T растёт к контуру)
        # сумма отрицательна, и конвекция греет область — знак сохранён
        # тем же, что был у прежней формулы.
        self.cum_conv += -float(np.sum(F)) * self._dt_substep

        # Коэффициенты подшага использованы — гасим, чтобы повторный вызов
        # add_accumulation не досчитал тот же вклад дважды.
        self._Phi_plus = None
        self._Phi_minus = None
        self._dt_substep = None

        # Накопление берётся ТОЧНО так, как его дискретизует схема
        # (\eqref{eq:energy_disc_full}, problem_statement.tex:1334):
        # cap_j = V_j (ρcp)^{n}_j / dt стоит в матрице и в
        # правой части ОДНИМ И ТЕМ ЖЕ множителем, поэтому шаговый вклад —
        # это V (ρcp)^{n} (T^{n+1} - T^{n}), а НЕ разность запасов
        # V[(ρcp)^{n+1} T^{n+1} - (ρcp)^{n} T^{n}].
        # Разница между ними — член Σ V T^{n} [(ρcp)^{n+1} - (ρcp)^{n}],
        # который на табличном PVT давал 20 % невязки (BUG-004): свойства
        # дрейфуют систематически, и дрейф умножается на абсолютную
        # T ~ 350 K, а не на приращение ΔT ~ 1 K.
        #
        # (ρcp)_eff — та самая, что стоит в матрице как cap_j
        # (tridiag.assemble_tridiag, cap), взятая на T_old. Постобработка брала её на
        # новой T; при константных c_p это эквивалентно, но здесь
        # эквивалентность больше не требуется.
        self.delta_E += float(np.sum(rho_cp_eff * V * (T_new - T_prev)))

        # ── Кондуктивный поток через контур ──
        # Внутренние грани телескопируются: поток из ячейки в ячейку
        # сокращается при суммировании по объёму. Остаётся только контур,
        # где стоит ГУ Дирихле T = T_ext:
        #     E_cond = Σ_n Q_T_ext (T_ext - T^{n+1}_{N-1}) Δt_n
        # T берётся НОВАЯ: схема неявная, в СЛАУ Q_T_ext·T^{n+1}_{N-1}
        # стоит в диагонали b[N-1], а Q_T_ext·T_ext —
        # в правой части d[N-1] (tridiag.assemble_tridiag, блок контура), см.
        # \eqref{eq:tridiag_b} и \eqref{eq:tridiag_d}.
        # Та же логика — у конвективного члена выше (BUG-007).
        #
        # Проводимость посчитана решателем (передана в add_substep), а не
        # пересчитана здесь: иначе баланс разойдётся со схемой — ровно так
        # возник BUG-004. Это ещё и защита от повторения BUG-002 (двойной
        # ln в кондуктивной проводимости).
        #
        # При λ = 0 Q_T_ext = geom·λ_eff[-1] тождественно ноль
        # (tridiag.compute_conductive_transmissibility), и член обнуляется
        # сам — без ветвлений по конфигу.
        self.cum_cond += float(
            self._Q_T_ext * (self._T_ext - T_new[N - 1]) * dt)

    # ──────────────────────────────────────────────────────
    # Снимок для записи в историю
    # ──────────────────────────────────────────────────────

    def snapshot(self) -> dict:
        """Накопленные значения на текущий момент — СКАЛЯРЫ.

        Ключи — CUMULATIVE_KEYS. Производные величины (total, residual,
        rel_residual) здесь не считаются: они собираются из этих шести
        при формировании массивов по всей истории.
        """
        return dict(
            delta_E=self.delta_E,
            cum_adiab=self.cum_adiab,
            cum_conv=self.cum_conv,
            cum_jt=self.cum_jt,
            cum_deg=self.cum_deg,
            cum_cond=self.cum_cond,
        )
