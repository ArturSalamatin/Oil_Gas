"""Константы пересчёта единиц и стандартные условия; расчёт ведётся в СИ.

Пересчёт: ``BAR_TO_PA``, ``PA_TO_BAR``, ``PSI_TO_PA``, ``PA_TO_PSI``
(давление); ``CP_TO_PA_S``, ``PA_S_TO_CP`` (вязкость); ``MD_TO_M2``,
``M2_TO_MD`` (проницаемость, 1 мД = 9.869233e-16 м²); ``DAY_TO_S``,
``S_TO_DAY``, ``MIN_TO_S``, ``HOUR_TO_S`` (время); ``SCF_PER_M3`` —
множитель пересчёта газосодержания из м³ст/м³ст в scf/STB (в баррели
5.6146 куб. фута). Стандартные условия: ``P_STD`` = 101325 Па,
``T_STD`` = 288.71 К (60 °F); ``RHO_WATER_STD``, ``RHO_AIR_STD`` —
плотности воды и воздуха в стандартных условиях, кг/м³.
"""

# ── Давление ──────────────────────────────────────────────────
BAR_TO_PA = 1.0e5
PA_TO_BAR = 1.0e-5
PSI_TO_PA = 6894.757
PA_TO_PSI = 1.0 / 6894.757

# ── Вязкость ──────────────────────────────────────────────────
CP_TO_PA_S = 1.0e-3
PA_S_TO_CP = 1.0e3

# ── Проницаемость ─────────────────────────────────────────────
MD_TO_M2 = 9.869233e-16
M2_TO_MD = 1.0 / 9.869233e-16

# ── Время ─────────────────────────────────────────────────────
DAY_TO_S = 86400.0
S_TO_DAY = 1.0 / 86400.0
MIN_TO_S = 60.0
HOUR_TO_S = 3600.0

# ── Объём (PVT) ───────────────────────────────────────────────
SCF_PER_M3 = 5.6146

# ── Плотности при стандартных условиях ─────────────────────────
RHO_WATER_STD = 999.0      # кг/м³
RHO_AIR_STD = 1.225         # кг/м³

# ── Стандартные условия ───────────────────────────────────────
P_STD = 101325.0            # Па
