def _ref_cell_properties(pvt, rock, p, Sg, Rs, T_old):
    """Эффективные свойства в ячейках. eq:main_rhocpeff, eq:lambda_eff.

    (ρcp)_eff = (1-φ)·(ρcp)_s + φ·Σ_α S_α·ρ_α·c_pα   [Дж/(м³·К)]
    λ_eff     = (1-φ)·λ_s     + φ·Σ_α S_α·λ_α        [Вт/(м·К)]

    So берётся как 1 - Sg, как в ядре: тождество So + Sg = 1 обязано
    выполняться точно.
    """
    So = 1.0 - Sg
    phi = rock.porosity

    # PVT берём из ядра — воспроизводить корреляции здесь бессмысленно,
    # тест проверяет сборку матрицы, а не PVT-модель.
    props = dict(
        Bo=pvt.Bo(p, Rs),
        rho_o=pvt.rho_o(p, Rs),
        rho_g=pvt.rho_g(p),
        c_p_o=pvt.c_p_oil(p, T_old),
        c_p_g=pvt.c_p_gas(p, T_old),
        mu_JT_o=pvt.mu_JT_oil(p, T_old),
        mu_JT_g=pvt.mu_JT_gas(p, T_old),
        L=pvt.L_degas(p, T_old),
        So=So,
    )
    props['rho_cp_eff'] = ((1.0 - phi) * rock.rho_cp_solid
                           + phi * (So * props['rho_o'] * props['c_p_o']
                                    + Sg * props['rho_g'] * props['c_p_g']))
    props['lambda_eff'] = ((1.0 - phi) * rock.lambda_solid
                           + phi * (So * rock.lambda_oil
                                    + Sg * rock.lambda_gas))
    return props


def _upstream(flux_at_face, face):
    """Ячейка выше по потоку для внутренней грани. eq:upstream_operator.

    Конвенция знаков (vault/knowledge/decisions/конвенции-знаков.md):
    положительное направление — от скважины, в сторону роста r.
    Значит flux >= 0 — течение слева направо, берём левую ячейку face-1;
    flux < 0 — течение к скважине, берём правую ячейку face.

    Ноль отнесён к левой ветке (>=), как и в ядре: при нулевом потоке
    конвективный вклад всё равно нулевой, выбор ячейки ни на что не влияет.
    """
    return face - 1 if flux_at_face >= 0 else face


def _ref_convective(Q_o, Q_g, rho_o, rho_g, c_p_o, c_p_g, N, ext):
    """Конвективные коэффициенты на гранях. eq:energy_conv_face.

    Φ_α = ρ_α·c_pα·Q_α  [Вт/К], свойства из ячейки выше по потоку.
    Направление определяется РАЗДЕЛЬНО по каждой фазе — фазы могут
    течь в разные стороны (прямо оговорено в eq:energy_conv_face).
    Это заготовка на будущее, если учитывается капиллярное давление
    и тензор проницаемости.

    Φ⁺ = Σ_α max(Φ_α, 0) >= 0, Φ⁻ = Σ_α min(Φ_α, 0) <= 0.
    На штатных конфигах течения от скважины на внутренних гранях физически
    нет: Φ⁺ = 0, а на останове (16, 17) и на фронте волны давления
    примера 18 (VAL-005) — шум Ньютона, Q_o до 1.4e-11 м³/с. Вклад ветки
    при этом на порядки ниже допуска сверки и формулу не проверяет — ветку
    Φ⁺ в JT-вкладе проверяет синтетика test_ref_jt_outflow_matches_hand_formula
    (BUG-023).

    Возвращает Φ_o, Φ_g, Φ⁺, Φ⁻ — все [N+1].
    """
    Phi_o = np.zeros(N + 1)
    Phi_g = np.zeros(N + 1)

    # определяем, с какого направления потоком приносится энергия,
    # вызов функции _upstream, и вычисляем поток энергии Φ_o, Φ_g 
    # через грань

    # ── Внутренние грани ──
    for f in range(1, N):
        up_o = _upstream(Q_o[f], f)
        Phi_o[f] = rho_o[up_o] * c_p_o[up_o] * Q_o[f]

        up_g = _upstream(Q_g[f], f)
        Phi_g[f] = rho_g[up_g] * c_p_g[up_g] * Q_g[f]

    # ── Забой (f=0) ──
    # Флюид уходит в скважину, выше по потоку — ячейка 0
    # (ssec:bc_disc, подпараграф «Температура»).
    #
    # Закачка через забой не допускается: расходы обязаны быть
    # НЕПОЛОЖИТЕЛЬНЫМИ. Конвенция знаков проекта — положительное
    # направление от скважины, поэтому Q < 0 это добыча (штатный режим),
    # а Q > 0 — нагнетание в пласт.
    #
    # Ноль допустим: при p_wf = p[0] потока нет и вклад нулевой; при
    # p_wf > p[0] скважина закрыта, и потоки тоже нулевые
    # (eq:bc_pwf_shutin) — закачки гидродинамика не даёт ни на одном пути.
    assert Q_o[0] <= 0.0, (
        f"закачка нефти через забой: Q_o[0] = {Q_o[0]:.6e} м³пл/с > 0. "
        "Режим не определён постановкой — температура втекающего потока "
        "не задана (ssec:bc_disc)")
    assert Q_g[0] <= 0.0, (
        f"закачка газа через забой: Q_g[0] = {Q_g[0]:.6e} м³пл/с > 0. "
        "Режим не определён постановкой — температура втекающего потока "
        "не задана (ssec:bc_disc)")

    Phi_o[0] = rho_o[0] * c_p_o[0] * Q_o[0]
    Phi_g[0] = rho_g[0] * c_p_g[0] * Q_g[0]

    # ── Контур (f=N) ── eq:bc_props_ext (74)
    # По знаку расхода, раздельно по фазам: отток наружу — свойства
    # из ячейки N-1, приток — при условиях контура (p_0, T_0, Rs^0).
    # Газовая ветвь при Sg|ext = 0 умножается на Q_g = 0, поэтому
    # значение ρ_g, c_p_g на результат не влияет; формула всё равно
    # выписана полностью — она верна и при Sg_ext > 0.
    Phi_o[N] = ((rho_o[N - 1] * c_p_o[N - 1] if Q_o[N] >= 0
                 else ext['rho_o'] * ext['c_p_o']) * Q_o[N])
    Phi_g[N] = ((rho_g[N - 1] * c_p_g[N - 1] if Q_g[N] >= 0
                 else ext['rho_g'] * ext['c_p_g']) * Q_g[N])

    return (Phi_o, Phi_g,
            # Φ⁺
            np.maximum(Phi_o, 0.0) + np.maximum(Phi_g, 0.0),
            # Φ⁻
            np.minimum(Phi_o, 0.0) + np.minimum(Phi_g, 0.0))


def _ref_conductive(grid, lambda_eff):
    """Кондуктивная проводимость граней. eq:heat_cond_disc.

    ФОРМА ДОКУМЕНТА (eq:heat_cond_disc со средним eq:face_interp):
        Q_T = 2πh · λ^{j+1/2} / ln(r_{j+1}/r_j),
        λ^{j+1/2} = (w_L + w_R) · (w_L/λ_L + w_R/λ_R)^{-1}   [гармоническое
        среднее с нормированными логарифмическими весами]

    Ядро считает это иначе — как последовательные кольцевые сопротивления
    Q_T = 2πh / (w_L/λ_L + w_R/λ_R). Формы алгебраически тождественны, так
    как w_L + w_R = ln(r_{j+1}/r_j).
    Здесь намеренно записана форма документа: именно ошибка в этом месте
    (двойной ln) была содержанием BUG-002. До BUG-027 сам документ записывал
    среднее без множителя (w_L + w_R); эталон буквально по такому документу
    завысил бы проводимость в 1/ln(r_{j+1}/r_j) раз. Самопроверка —
    test_ref_conductive_matches_annulus_solution.

    При λ = 0 сопротивление бесконечно, проводимость — ноль. Считаем по
    маске λ > 0: деления на нуль не происходит вовсе.

    Контур: соседней ячейки нет, λ берётся из ячейки N-1 (ssec:bc_disc).

    Возвращает Q_T_internal [N-1] (>= 0) и Q_T_ext (скаляр, >= 0).
    """
    # При N = 1 внутренних граней нет: веса и срезы пустые, вся арифметика
    # ниже даёт пустой массив — отдельная ветка не нужна.
    w_L = grid.log_weights_left      # ln(r_face / r_center_left)   [N-1]
    w_R = grid.log_weights_right     # ln(r_center_right / r_face)  [N-1]
    lam_L = lambda_eff[:-1]
    lam_R = lambda_eff[1:]
    r_c = grid.r_centers

    # λ = 0 хотя бы с одной стороны грани → кольцевое сопротивление w/λ
    # бесконечно → гармоническое среднее и проводимость равны нулю.
    # Считаем по маске: деление на нуль не выполняется.
    ok = np.minimum(lam_L, lam_R) > 0.0
    lam_face = np.zeros_like(w_L)
    lam_face[ok] = ((w_L[ok] + w_R[ok])
                    / (w_L[ok] / lam_L[ok] + w_R[ok] / lam_R[ok]))

    # Форма документа: делим на ln(r_{j+1}/r_j). Он сокращается с множителем
    # (w_L + w_R) среднего, но сокращать его здесь НЕЛЬЗЯ — эталон
    # воспроизводит запись документа буквально. Без множителя (w_L + w_R)
    # ln остался бы в знаменателе дважды: BUG-002 в коде, BUG-027 в документе.
    Q_T_internal = (2.0 * np.pi * grid.h * lam_face
                    / np.log(r_c[1:] / r_c[:-1]))

    Q_T_ext = (2.0 * np.pi * grid.h
               / np.log(grid.R_ext / grid.r_centers[-1]) * lambda_eff[-1])

    return Q_T_internal, Q_T_ext


# ── Самопроверка _ref_conductive: точное решение в кольце ──

def test_ref_conductive_matches_annulus_solution():
    """Проводимость граней в форме документа против точного решения в кольце.

    Зачем. Эталон следует форме документа: eq:heat_cond_disc со средним
    eq:face_interp. До BUG-027 документ записывал среднее без нормировки
    весов — при однородной λ оно равнялось λ/ln(r_{j+1}/r_j), и поток получал
    ln² в знаменателе: дефект BUG-002, перенесённый в постановку. Эталон,
    переписанный буквально по такому документу, завысил бы проводимость в
    1/ln(r_{j+1}/r_j) раз (на сетке примера 14 — в 46 раз), а сверка
    test_matrix_matches_reference увидела бы это только в медленном прогоне.

    Ожидание — стационарная теплопроводность, а не код решателя:
      однородная λ: Q_T = 2πhλ / ln(r_{j+1}/r_j)  (T = C1·ln r + C2);
      λ_L в слое [r_j, r_{j+1/2}], λ_R в слое [r_{j+1/2}, r_{j+1}]:
        сопротивления складываются,
        Q_T = 2πh / (ln(r_{j+1/2}/r_j)/λ_L + ln(r_{j+1}/r_{j+1/2})/λ_R);
      контур: Q_T_ext = 2πh·λ_{N-1} / ln(R_ext/r_{N-1})  (ssec:bc_disc).
    Сетка — r_w, R_ext примера 14, но N = 20: ln(r_{j+1}/r_j) ≈ 0.38, двойной
    ln дал бы расхождение в 2.6 раза. Чередование λ по ячейкам — на каждой
    грани два слоя с разной λ. Решатель проверяется той же формулой.
    """
    grid = LogRadialGrid(0.1, 200.0, 10.0, 20, 1e-13)
    N = grid.N
    r_c = grid.r_centers
    r_f = grid.r_faces[1:-1]          # внутренние грани [N-1]
    two_pi_h = 2.0 * np.pi * grid.h

    # Однородная λ: в знаменателе один ln
    lam = 1.228
    Q_int, Q_ext = _ref_conductive(grid, np.full(N, lam))
    np.testing.assert_allclose(
        Q_int, two_pi_h * lam / np.log(r_c[1:] / r_c[:-1]), rtol=1e-12,
        err_msg="однородная λ: в знаменателе один ln (BUG-002, BUG-027)")
    np.testing.assert_allclose(
        Q_ext, two_pi_h * lam / np.log(grid.R_ext / r_c[-1]), rtol=1e-12,
        err_msg="контур: ssec:bc_disc")

    # Два слоя кольца с разной λ: сопротивления складываются
    lam_cells = np.where(np.arange(N) % 2 == 0, 1.228, 0.3)
    R_layers = (np.log(r_f / r_c[:-1]) / lam_cells[:-1]
                + np.log(r_c[1:] / r_f) / lam_cells[1:])
    Q_int, _ = _ref_conductive(grid, lam_cells)
    np.testing.assert_allclose(
        Q_int, two_pi_h / R_layers, rtol=1e-12,
        err_msg="эталон: сопротивления двух слоёв кольца складываются")

    # compute_conductive_transmissibility читает только сетку; массив по
    # граням [N+1] (DEBT-020), внутренние — Q_solver[1:N]
    Q_solver = TridiagEnergySolver(grid, None, None) \
        .compute_conductive_transmissibility(lam_cells, N)
    np.testing.assert_allclose(
        Q_solver[1:N], two_pi_h / R_layers, rtol=1e-12,
        err_msg="решатель compute_conductive_transmissibility")


def _ref_ext_properties(pvt, bc):
    """Свойства фаз при условиях контура. eq:bc_props_ext (74).

    Считается ЗДЕСЬ, а не вызовом TridiagEnergySolver._ext_properties:
    эталон обязан быть независимым от ядра, иначе он зафиксирует
    реализацию вместо постановки (шапка модуля). Из ядра берутся только
    PVT-корреляции — воспроизводить их тут бессмысленно.

    Sg на контуре не участвует: тепловые PVT-величины от насыщенности
    не зависят (FullPVT, pvt/base.py:60-107); отсутствие газовой фазы
    выражается через Q_g = 0 при k_rg|ext = 0 (eq:bc_flux_ext).
    """
    p_a = np.array([bc.p_ext])
    T_a = np.array([bc.T_ext])
    Rs_a = np.array([bc.Rs_ext])
    return dict(
        p=bc.p_ext,
        rho_o=pvt.rho_o(p_a, Rs_a)[0],
        rho_g=pvt.rho_g(p_a)[0],
        c_p_o=pvt.c_p_oil(p_a, T_a)[0],
        c_p_g=pvt.c_p_gas(p_a, T_a)[0],
        mu_JT_o=pvt.mu_JT_oil(p_a, T_a)[0],
        mu_JT_g=pvt.mu_JT_gas(p_a, T_a)[0])


def _ref_jt_face(f, Q_o, Q_g, mu_JT_o, mu_JT_g, p, N, ext, p_wf):
    """Свойства грани f для JT-вклада: (p слева, p справа, μ_JT_o, μ_JT_g).

    Давления — по ОБЕ стороны грани, перепад p справа − p слева — свойство
    самой грани, как Δp_{j∓1/2} в eq:QJT_disc. Одно давление «за гранью»
    не годится: внутренняя грань f — левая для ячейки f и правая для
    ячейки f-1, и значение p_f верно только для второй (BUG-023: эталон
    брал p_j вместо p_{j-1} на левой грани, перепад был нулевым).
    Три типа граней (ssec:bc_disc, «Источниковые члены на граничных гранях»):

    f = 0 — забой: (p_wf, p_0), выше по потоку — ячейка 0.
        Знак расхода здесь НЕ проверяется, в отличие от контура: закачка
        через забой запрещена assert-ом в _ref_convective, поэтому на пути
        build_reference Φ⁺[0] ≡ 0 и возвращаемый μ_JT умножается на нуль.
        Синтетика test_ref_jt_outflow_matches_hand_formula задаёт Φ⁺[0] > 0
        напрямую — там μ_JT из ячейки 0, как в решателе.

    0 < f < N — внутренняя: (p_{f-1}, p_f), μ_JT из ячейки выше по потоку
        СВОЕЙ фазы (eq:QJT_disc).

    f = N — контур: (p_{N-1}, p_ext) при любом знаке расхода (давление
        на контуре задано), а μ_JT — по знаку расхода (eq:bc_props_ext, 74):
        отток наружу берёт свойства ячейки N-1, приток — контурные.
    """
    if f == 0:
        return p_wf, p[0], mu_JT_o[0], mu_JT_g[0]
    if f == N:
        return (p[N - 1], ext['p'],
                mu_JT_o[-1] if Q_o[N] >= 0 else ext['mu_JT_o'],
                mu_JT_g[-1] if Q_g[N] >= 0 else ext['mu_JT_g'])
    return (p[f - 1], p[f],
            mu_JT_o[_upstream(Q_o[f], f)], mu_JT_g[_upstream(Q_g[f], f)])


def _ref_jt(Phi_o, Phi_g, mu_JT_o, mu_JT_g, Q_o, Q_g, p, N, ext, p_wf):
    """Вклад Джоуля—Томсона. eq:QJT_disc (АДВЕКТИВНАЯ форма, BUG-012).

    J_j = Σ_α [ μ_JT,α^{j-1/2}·Φ⁺_{α,j-1/2}·(p_j - p_{j-1})
              + μ_JT,α^{j+1/2}·Φ⁻_{α,j+1/2}·(p_{j+1} - p_j) ]   [Вт]

    Каждое слагаемое содержит ПЕРЕПАД давления на грани.
    Источник eq:main_QJT_muJT записан поточечно, через градиент давления,
    и дискретизация обязана воспроизводить именно эту форму. Прежняя
    запись J_j = J_{j+1/2} - J_{j-1/2} с J_f = Σ_α μ_JT·<Φ_α·p>_f
    дискретизировала div(μ_JT·Φ·p) и давала лишний член μ_JT·p_j·D_j,
    где D_j = Φ_{j+1/2} - Φ_{j-1/2} (BUG-012).

    Контрольное свойство: при однородном p член обращается в нуль
    тождественно — каждое слагаемое содержит разность давлений.

    Коэффициент μ_JT берётся из ячейки выше по потоку СВОЕЙ фазы.

    Граничные грани (ssec:bc_disc, «Источниковые члены на граничных
    гранях»). В отличие от температуры и состава, давление за обеими
    границами ЗАДАНО, поэтому обе граничные грани дают ненулевой вклад:
      - забой: p за гранью = p_wf, выше по потоку — ячейка 0;
      - контур: по знаку расхода (eq:bc_props_ext, 74):
            Q_α >= 0 (отток)  → μ_JT из ячейки N-1, p за гранью = p_ext;
            Q_α <  0 (приток) → μ_JT при условиях контура, p = p_ext.

    О полушаге на ОБЕИХ граничных гранях: перепад набирается на половине
    пути — (p_0 - p_wf) от центра ячейки 0 до забойной грани, (p_ext -
    p_{N-1}) от центра ячейки N-1 до грани контура, — тогда как на
    внутренних гранях перепад берётся между центрами, на полном шаге.
    Поправки не требуется ни там, ни там: длина пути уже учтена в Φ через
    проводимость грани, построенную на том же самом полушаге
    (trans_well на ln(r_0/r_well), trans_ext на ln(R_ext/r_{N-1}) против
    trans_internal на ln(r_{j+1}/r_j)). В произведении μ_JT·Φ·Δp длины
    сокращаются: Φ ∝ 1/ln(...) несёт обратную длину, Δp — прямую.
    См. постановку, «О полушаге».

    Возвращает J_jt [N].
    """
    J = np.zeros(N)

    for j in range(N):
        # Обе грани ячейки обрабатываются одной и той же функцией: разница
        # между забоем, внутренней гранью и контуром — только в выборе
        # давлений по сторонам грани и ячейки выше по потоку, и она вся
        # внутри _ref_jt_face.
        p_ll, p_lr, mu_o_l, mu_g_l = _ref_jt_face(
            j, Q_o, Q_g, mu_JT_o, mu_JT_g, p, N, ext, p_wf)
        p_rl, p_rr, mu_o_r, mu_g_r = _ref_jt_face(
            j + 1, Q_o, Q_g, mu_JT_o, mu_JT_g, p, N, ext, p_wf)

        # Перепад давления общий для обеих фаз на своей грани — вынесен
        # за сумму по фазам, как в eq:QJT_disc (знак Σ_α стоит снаружи).
        # На обеих гранях одна формула: p справа − p слева (BUG-023).
        dp_left = p_lr - p_ll            # на левой грани j-1/2: p_j − p_{j-1}
        dp_right = p_rr - p_rl           # на правой грани j+1/2: p_{j+1} − p_j

        # Σ_α μ_JT,α·Φ±_α на своей грани. Левая грань работает при Φ⁺ > 0,
        # правая — при Φ⁻ < 0. Эти две суммы НЕ приводятся друг к другу:
        # Φ⁺ берётся с левой грани, Φ⁻ с правой, и множители μ приходят
        # из разных ячеек выше по потоку.
        mu_Phi_left = (mu_o_l * max(Phi_o[j], 0.0)
                       + mu_g_l * max(Phi_g[j], 0.0))
        mu_Phi_right = (mu_o_r * min(Phi_o[j + 1], 0.0)
                        + mu_g_r * min(Phi_g[j + 1], 0.0))

        J[j] = mu_Phi_left * dp_left + mu_Phi_right * dp_right

    return J


